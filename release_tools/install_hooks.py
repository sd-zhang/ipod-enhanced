"""Install pre-commit and a direct pre-push guard without hiding dirty files."""

import subprocess
from pathlib import Path

from check_repository import git

MARKER = "# iPod Enhanced direct pre-push gate v1"
HOOK = """#!/bin/sh
# iPod Enhanced direct pre-push gate v1
repo_root=$(git rev-parse --show-toplevel) || exit 1
exec "$repo_root/.venv/bin/python" -B "$repo_root/release_tools/pre_push.py" "$@"
"""


def install(root: Path) -> None:
    hook = Path(git(root, "rev-parse", "--git-path", "hooks/pre-push").decode().strip())
    if not hook.is_absolute():
        hook = root / hook
    if hook.exists():
        content = hook.read_text()
        if MARKER not in content and "# File generated by pre-commit:" not in content:
            raise ValueError("Refusing to replace an existing custom pre-push hook")
    subprocess.run(
        [
            str(root / ".venv/bin/python"),
            "-m",
            "pre_commit",
            "install",
            "--hook-type",
            "pre-commit",
        ],
        cwd=root,
        check=True,
    )
    hook.parent.mkdir(parents=True, exist_ok=True)
    hook.write_text(HOOK)
    hook.chmod(0o755)
    print("Installed direct pre-push inventory, ref, history and verification gate")


if __name__ == "__main__":
    install(Path(__file__).resolve().parent.parent)
